package com.user.jobapplicationtracker.models;

import java.time.LocalDate;

import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.NoArgsConstructor;

@Entity // Tells JPA this class is a DB table
@Data // Lombok: generates getters/setters/toString
@NoArgsConstructor
@AllArgsConstructor
public class JobApplication {
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id; // database generated by id

    private String company; // company name

    private String position; // position applied to

    private String status; // e.g. "Applied", "Interviewing", "Rejected", etc

    private LocalDate appliedDate; // date applied
}
